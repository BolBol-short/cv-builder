export const isLang = (code) => LANGS.some((l) => l.code === code);

// t(key, fallback): current language → English → fallback → the key itself.
export function makeT(lang) {
  const dict = translations[lang] ?? translations.en;
  return (key, fallback) => dict[key] ?? translations.en[key] ?? fallback ?? key;
}

// Translate a stored option code ("female", "fluent"…) but pass free text through,
// so values typed by hand (or from old saves) still render.
export function optionLabel(t, group, value) {
  if (!value) return "";
  return t(`${group}.${value}`, value);
}
